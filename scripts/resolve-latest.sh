#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="${1:-$ROOT/vars/versions.yml}"

latest_provider() {
  local name="$1"
  python3 - <<PY
import json, urllib.request, re
name = "$name"
url = f"https://registry.opentofu.org/v1/providers/opentofu/{name}/versions"
raw = urllib.request.urlopen(url, timeout=30).read().decode()
data = json.loads(raw)
vers = sorted(data.get("versions", []), key=lambda v: [int(x) for x in re.findall(r"\d+", v)])
print(vers[-1] if vers else "0.0.0")
PY
}

tofu_ver="$(python3 - <<'PY'
import json, urllib.request
raw = urllib.request.urlopen("https://api.github.com/repos/opentofu/opentofu/releases/latest", timeout=30).read()
print(json.loads(raw)["tag_name"].lstrip("v"))
PY
)"
azurerm="$(latest_provider azurerm)"
aws_p="$(latest_provider aws)"
google_p="$(latest_provider google)"
random_v="$(latest_provider random)"
tls_v="$(latest_provider tls)"
azuread_v="$(latest_provider azuread)"

az_cli="$(python3 - <<'PY'
import json, urllib.request
raw = urllib.request.urlopen("https://api.github.com/repos/Azure/azure-cli/releases/latest", timeout=30).read()
tag = json.loads(raw)["tag_name"]
print(tag.replace("azure-cli-", ""))
PY
)"
aws_cli="$(python3 - <<'PY'
import json, urllib.request
raw = urllib.request.urlopen("https://api.github.com/repos/aws/aws-cli/tags", timeout=30).read()
print(json.loads(raw)[0]["name"])
PY
)"
gcloud_cli="502.0.0"
td_ver="0.20.0"

mkdir -p "$(dirname "$OUT")"
cat >"$OUT" <<EOF
# GENERATED by scripts/resolve-latest.sh — do not edit by hand
OpenTofuVersion: "${tofu_ver}"

ProviderSources:
  azure: opentofu/azurerm
  aws: opentofu/aws
  gcp: opentofu/google

ProviderVersions:
  azure: "${azurerm}"
  aws: "${aws_p}"
  gcp: "${google_p}"

ExtraProviderVersions:
  random: "${random_v}"
  tls: "${tls_v}"
  azuread: "${azuread_v}"

CliNames:
  azure: az
  aws: aws
  gcp: gcloud

CliVersions:
  azure: "${az_cli}"
  aws: "${aws_cli}"
  gcp: "${gcloud_cli}"

TerraformDocsVersion: "${td_ver}"
EOF
echo "Wrote $OUT"